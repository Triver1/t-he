"""Generates wall_waves.scad: thin wave grooves cut into the carry case frame's outer face, one closed loop per line.
The wave counts around the loop are whole numbers, so every line closes on itself.
Usage: wall_waves.py <outline.svg> <wall_waves.scad>
"""
import bisect
import json
import math
import re
import sys

LINES, Z0, Z1 = 13, 4.6, 53.7
LINE_W, DEPTH, ABOVE, STEP = 0.5, 0.3, 0.2, 2.0
SWELL, CHOP = 1.1, 0.35
SWELL_LEN, CHOP_LEN = 26.0, 11.0

pts = [(float(a), -float(b)) for a, b in re.findall(r'(-?[\d.]+),(-?[\d.]+)', open(sys.argv[1]).read())]
if pts[0] == pts[-1]:
    pts.pop()
if sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(pts, pts[1:] + pts[:1])) < 0:
    pts.reverse()
closed = pts + pts[:1]
cum = [0.0]
for a, b in zip(closed, closed[1:]):
    cum.append(cum[-1] + math.dist(a, b))
total = cum[-1]
swell, chop = round(total / SWELL_LEN), round(total / CHOP_LEN)


def at(s):
    s %= total
    i = min(bisect.bisect_right(cum, s) - 1, len(pts) - 1)
    t = (s - cum[i]) / (cum[i + 1] - cum[i])
    return closed[i][0] + t * (closed[i + 1][0] - closed[i][0]), closed[i][1] + t * (closed[i + 1][1] - closed[i][1])


def normal(s):
    a, b = at(s - 0.4), at(s + 0.4)
    d = math.dist(a, b) or 1.0
    return (b[1] - a[1]) / d, -(b[0] - a[0]) / d   # outward on a counter-clockwise loop


stations = sorted(set(round(s, 3) for s in cum[:-1]) | {round(i * STEP, 3) for i in range(int(total / STEP))})
stations = [s for s, nxt in zip(stations, stations[1:] + [stations[0] + total]) if nxt - s > 0.05]


def wave(s, i):
    a = 2 * math.pi * s / total
    return SWELL * math.sin(swell * a + i * 0.9) + CHOP * math.sin(chop * a - i * 1.7)


def loop(i):
    zc = Z0 + i * (Z1 - Z0) / (LINES - 1)
    v = []
    for s in stations:
        (x, y), (nx, ny) = at(s), normal(s)
        z = zc + wave(s, i)
        for d, dz in ((ABOVE, -LINE_W / 2), (ABOVE, LINE_W / 2), (-DEPTH, LINE_W / 2), (-DEPTH, -LINE_W / 2)):
            v.append([round(x + nx * d, 3), round(y + ny * d, 3), round(z + dz, 3)])
    n = len(stations)
    f = [[4 * j + k, 4 * j + (k + 1) % 4, 4 * ((j + 1) % n) + (k + 1) % 4, 4 * ((j + 1) % n) + k] for j in range(n) for k in range(4)]
    return v, f


def volume(v, faces):
    t = 0.0
    for q in faces:
        a = v[q[0]]
        for b, c in zip(q[1:], q[2:]):
            t += (a[0] * (v[b][1] * v[c][2] - v[b][2] * v[c][1]) - a[1] * (v[b][0] * v[c][2] - v[b][2] * v[c][0])
                  + a[2] * (v[b][0] * v[c][1] - v[b][1] * v[c][0])) / 6
    return t


body = []
for i in range(LINES):
    v, f = loop(i)
    if volume(v, f) > 0:                           # OpenSCAD lists a face's corners clockwise from outside
        f = [q[::-1] for q in f]
    body.append(f'polyhedron({json.dumps(v, separators=(",", ":"))},{json.dumps(f, separators=(",", ":"))});')
open(sys.argv[2], 'w').write('// generated by wall_waves.py\nmodule wall_waves() {\n' + '\n'.join(body) + '\n}\n')
print(f'{total:.1f} mm loop, {LINES} lines, {swell} swells, {chop} chop waves, {len(stations)} stations')
