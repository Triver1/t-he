"""Reads the left half of totem_he.kicad_pcb and writes ../case/mock_parts.scad: component positions for the PCB mock
(the case mirrors them for the right)."""
import re
from halves import BOARD_W

s = open('totem_he.kicad_pcb').read()
# older KiCad files put the uuid after the position, newer ones before it; both forms are matched
fps = [(m[1].split(':')[-1], float(m[2]), -float(m[3]), float(m[4] or 0)) for m in re.finditer(
    r'\(footprint "([^"]+)"\s*\(layer "[^"]+"\)\s*(?:\(uuid "[^"]*"\)\s*)?\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', s)]
parts = [f'  ["{n}", {x:.3f}, {y:.3f}, {r:.3f}],' for n, x, y, r in fps if n != 'mounting_hole_plated' and x <= BOARD_W]
lines = ['// generated by gen_mock.py from totem_he.kicad_pcb: [name, x, y, rot]', 'mock_parts = [', *parts, '];']
open('../case/mock_parts.scad', 'w').write('\n'.join(lines) + '\n')
print(len(parts), 'footprints')
