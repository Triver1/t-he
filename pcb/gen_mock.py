"""Reads out/<side>/pcbs/*.kicad_pcb and writes mock_parts_<side>.scad: component boxes for the PCB mock."""
import sys, re
for side in ('left', 'right'):
    s = open(f'out/{side}/pcbs/totem_he_{side}.kicad_pcb').read()
    fps = [(m[1].split(':')[-1], float(m[2]), -float(m[3]), float(m[4] or 0)) for m in re.finditer(r'\(footprint "([^"]+)"\s*\(layer "[^"]+"\)\s*\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', s)]
    lines = [f'// generated by gen_mock.py from totem_he_{side}.kicad_pcb: [name, x, y, rot]', f'mock_parts = [']
    for n, x, y, r in fps:
        if n in ('mounting_hole_plated',): continue
        lines.append(f'  ["{n}", {x:.3f}, {y:.3f}, {r:.3f}],')
    lines.append('];')
    open(f'../mock_parts_{side}.scad', 'w').write('\n'.join(lines) + '\n')
    print(side, len(fps), 'footprints')
